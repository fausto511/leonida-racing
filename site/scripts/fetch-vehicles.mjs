#!/usr/bin/env node
// RS-0052 (DEC-0089): the Supabase database is the single source of vehicle
// data. This script pulls vehicles, their current measured values (with
// provenance) and the game releases, and writes them to
// src/data/vehicles.generated.json, which the Astro build reads.
//
// - CI (deploy-pages.yml) runs it before every build with the public anon key,
//   so each deploy ships the current database state.
// - Without PUBLIC_SUPABASE_URL / PUBLIC_SUPABASE_ANON_KEY it keeps the
//   committed JSON (offline/local builds). That file is a generated cache:
//   never edit it by hand -- change the database (Moderator > Vehicles).
// - With credentials, any fetch error fails the build, so a broken fetch
//   never deploys an empty or stale garage.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const URL_ = process.env.PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL;
const KEY = process.env.PUBLIC_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY;
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/data/vehicles.generated.json');

async function get(pathAndQuery) {
  const res = await fetch(`${URL_}/rest/v1/${pathAndQuery}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } });
  if (!res.ok) throw new Error(`${pathAndQuery}: ${res.status} ${await res.text()}`);
  return res.json();
}

if (!URL_ || !KEY) {
  console.log('fetch-vehicles: no Supabase credentials -- keeping the committed vehicles.generated.json');
  process.exit(0);
}

const [vehicles, values, releases] = await Promise.all([
  get('vehicles?select=vehicle_id,make,model,manufacturer_logo_slug,classes,seats,drive,acquisition,has_photo,release_id,first_seen_in,first_seen_url,first_seen_timestamp,real_life_inspiration&order=make.asc,model.asc'),
  get('vehicle_values?status=eq.current&select=vehicle_id,metric,value,source_type,method,game_release_id,platform,measured_at,evidence_url&order=vehicle_id.asc,metric.asc'),
  get('game_releases?select=release_id,name,kind,release_date,sort_order&order=sort_order.asc'),
]);
if (!Array.isArray(vehicles) || vehicles.length === 0) throw new Error('fetch-vehicles: database returned no vehicles -- refusing to build an empty garage');

const data = { note: 'GENERATED by site/scripts/fetch-vehicles.mjs from Supabase -- do not edit by hand', vehicles, values, releases };
await writeFile(OUT, JSON.stringify(data, null, 1) + '\n');
console.log(`fetch-vehicles: ${vehicles.length} vehicles, ${values.length} values, ${releases.length} releases`);
